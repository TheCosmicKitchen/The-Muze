// Builds data/pages.js for Blackout from Project Gutenberg plain-text files.
// Usage: node tools/build-pages.mjs <folder with <id>.txt files>
// Download a book with: https://www.gutenberg.org/cache/epub/<id>/pg<id>.txt
import fs from 'node:fs';
import path from 'node:path';

const BOOKS = [
  [1342, 'Pride and Prejudice', 'Jane Austen'],
  [84, 'Frankenstein', 'Mary Shelley'],
  [2701, 'Moby-Dick', 'Herman Melville'],
  [11, "Alice's Adventures in Wonderland", 'Lewis Carroll'],
  [1661, 'The Adventures of Sherlock Holmes', 'Arthur Conan Doyle'],
  [345, 'Dracula', 'Bram Stoker'],
  [64317, 'The Great Gatsby', 'F. Scott Fitzgerald'],
  [514, 'Little Women', 'Louisa May Alcott'],
  [1260, 'Jane Eyre', 'Charlotte Brontë'],
  [289, 'The Wind in the Willows', 'Kenneth Grahame'],
  [98, 'A Tale of Two Cities', 'Charles Dickens'],
  [205, 'Walden', 'Henry David Thoreau'],
  [174, 'The Picture of Dorian Gray', 'Oscar Wilde'],
  [35, 'The Time Machine', 'H. G. Wells'],
  [76, 'Adventures of Huckleberry Finn', 'Mark Twain'],
  [43, 'Strange Case of Dr Jekyll and Mr Hyde', 'Robert Louis Stevenson'],
];
const PER_BOOK = 30, MIN = 110, MAX = 165;

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-pages.mjs <dir>'); process.exit(1); }

const wc = s => s.split(/\s+/).filter(Boolean).length;
const isProse = p => {
  if (p.length < 60) return false;
  if (/^(CHAPTER|BOOK|PART|VOLUME|STAVE|LETTER)\b/i.test(p)) return false;
  if (/\[|\]|\bIllustration\b|http|\d{3,}/.test(p)) return false;
  const caps = (p.match(/[A-Z]/g) || []).length;
  return caps / p.length < 0.12;
};

const books = [], pages = [];
BOOKS.forEach(([id, title, author], bi) => {
  let txt = fs.readFileSync(path.join(dir, `${id}.txt`), 'utf8').replace(/\r/g, '');
  const a = txt.search(/\*\*\* ?START OF/), z = txt.search(/\*\*\* ?END OF/);
  txt = txt.slice(txt.indexOf('\n', a) + 1, z > 0 ? z : undefined);
  const paras = txt.split(/\n\s*\n/)
    .map(p => p.replace(/\s+/g, ' ').replace(/_/g, '').replace(/--/g, '—').trim())
    .filter(Boolean);
  // Skip the front matter (contents, prefaces): start 4% in.
  const start = Math.floor(paras.length * 0.04);
  const out = [];
  const step = Math.max(1, Math.floor((paras.length - start) / (PER_BOOK * 1.6)));
  for (let i = start; i < paras.length && out.length < PER_BOOK; i += step) {
    const chunk = [];
    let n = 0, j = i;
    while (j < paras.length && n < MIN && isProse(paras[j])) { chunk.push(paras[j]); n += wc(paras[j]); j++; }
    if (n < MIN) continue;
    // Trim to MAX words, ending on a sentence.
    let words = chunk.join('\n').split(/ /);
    if (wc(chunk.join(' ')) > MAX) {
      let text = '', count = 0;
      for (const w of words) { count += wc(w); if (count > MAX) break; text += (text ? ' ' : '') + w; }
      const cut = Math.max(text.lastIndexOf('. '), text.lastIndexOf('? '), text.lastIndexOf('! '), text.lastIndexOf('.\n'), text.lastIndexOf('."'), text.lastIndexOf('.”'));
      if (cut < 0 || wc(text.slice(0, cut + 2)) < MIN * 0.8) continue;
      text = text.slice(0, cut + 2).trim();
      out.push(text);
    } else out.push(chunk.join('\n'));
  }
  books.push({ t: title, a: author, id });
  out.forEach(t => pages.push({ b: bi, t }));
  console.log(`${title}: ${out.length} pages`);
});

const js = `// Generated by tools/build-pages.mjs from Project Gutenberg texts (public domain).\n` +
  `window.BOOKS=${JSON.stringify(books)};\nwindow.PAGES=${JSON.stringify(pages)};\n`;
fs.mkdirSync('data', { recursive: true });
fs.writeFileSync('data/pages.js', js);
console.log(`${pages.length} pages, ${(js.length / 1024).toFixed(0)} KB`);
