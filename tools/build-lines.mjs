// Builds data/lines.js for Cut-up from Project Gutenberg poetry collections.
// Usage: node tools/build-lines.mjs <folder with <id>.txt files>
import fs from 'node:fs';
import path from 'node:path';

const BOOKS = [
  [12242, 'Emily Dickinson'],
  [1322, 'Walt Whitman'],
  [1041, 'William Shakespeare'],
  [23684, 'John Keats'],
  [10031, 'Edgar Allan Poe'],
  [1934, 'William Blake'],
  [3026, 'Robert Frost'],
  [16950, 'Christina Rossetti'],
  [8672, 'John Clare'],
];
const PER_BOOK = 140;

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-lines.mjs <dir>'); process.exit(1); }

const authors = [], lines = [];
BOOKS.forEach(([id, author], ai) => {
  let txt = fs.readFileSync(path.join(dir, `${id}.txt`), 'utf8').replace(/\r/g, '');
  const a = txt.search(/\*\*\* ?START OF/), z = txt.search(/\*\*\* ?END OF/);
  const raw = txt.slice(txt.indexOf('\n', a) + 1, z > 0 ? z : undefined).split('\n');
  const len = i => (raw[i] || '').trim().length;
  const ok = [];
  raw.forEach((l, i) => {
    const s = l.trim().replace(/_/g, '').replace(/--/g, '—').replace(/\s+/g, ' ');
    if (s.length < 18 || s.length > 58) return;
    // Wrapped prose sits between long lines; verse doesn't.
    if (len(i - 1) >= 64 || len(i + 1) >= 64) return;
    if (!/^[“"‘'(]?[A-Za-z]/.test(s) || /\d|\[|\]|Gutenberg|CHAPTER|^[A-Z\s.,'’-]+$/.test(s)) return;
    if ((s.match(/[A-Z]/g) || []).length / s.length > 0.25) return;
    ok.push(s.replace(/^[“"‘'(]+|[”"’')]+$/g, '').replace(/[,;:—-]+$/, ''));
  });
  const uniq = [...new Set(ok)];
  // Skip the front and back matter, then sample evenly.
  const body = uniq.slice(Math.floor(uniq.length * 0.03), Math.floor(uniq.length * 0.97));
  const step = Math.max(1, body.length / PER_BOOK);
  for (let k = 0; k < body.length && k / step < PER_BOOK; k += step) lines.push({ a: ai, t: body[Math.floor(k)] });
  authors.push(author);
  console.log(`${author}: ${uniq.length} candidate lines`);
});

const js = `// Generated by tools/build-lines.mjs from Project Gutenberg poetry (public domain).\n` +
  `window.POETS=${JSON.stringify(authors)};\nwindow.LINES=${JSON.stringify(lines)};\n`;
fs.mkdirSync('data', { recursive: true });
fs.writeFileSync('data/lines.js', js);
console.log(`${lines.length} lines, ${(js.length / 1024).toFixed(0)} KB`);
