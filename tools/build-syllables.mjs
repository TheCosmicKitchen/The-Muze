// Builds data/syllables.js for Haiku Hunt: every word on the novel pages that the rules in
// muze.js count wrongly, with its count from the CMU Pronouncing Dictionary.
// Usage: node tools/build-syllables.mjs <path to cmudict.dict>
// Dictionary: https://raw.githubusercontent.com/cmusphinx/cmudict/master/cmudict.dict
import fs from 'node:fs';

const dict = process.argv[2];
if (!dict) { console.error('usage: node tools/build-syllables.mjs <cmudict.dict>'); process.exit(1); }

// A word can have several pronunciations; the first listed is the usual one.
const cmu = new Map();
for (const line of fs.readFileSync(dict, 'utf8').split('\n')) {
  const m = line.match(/^([a-z'.-]+)(\(\d+\))?\s+(.+?)(\s+#.*)?$/); if (!m) continue;
  const n = (m[3].match(/\d/g) || []).length;
  if (!cmu.has(m[1])) cmu.set(m[1], []);
  cmu.get(m[1]).push(n);
}

globalThis.window = {}; globalThis.location = { hash: '', pathname: '/' }; globalThis.localStorage = { getItem() { return null; } };
const Muze = new Function(fs.readFileSync('muze.js', 'utf8') + ';return Muze;')();
new Function('window', fs.readFileSync('data/pages.js', 'utf8'))(window);

const words = new Set();
for (const p of window.PAGES) for (const t of p.t.split(/[\s—-]+/)) {
  const w = t.replace(/^[^\p{L}]+|[^\p{L}’']+$/gu, '').toLowerCase().replace(/’/g, "'");
  if (w) words.add(w);
}
const table = {};
for (const w of [...words].sort()) {
  const c = cmu.get(w);
  if (c && !c.includes(Muze.syllables(w))) table[w] = c[0];
}
const js = `// Generated by tools/build-syllables.mjs. Words the rules in muze.js miscount, with counts from the\n` +
  `// CMU Pronouncing Dictionary (Copyright (c) Carnegie Mellon University, BSD licence).\nwindow.SYLLABLES=${JSON.stringify(table)};\n`;
fs.writeFileSync('data/syllables.js', js);
console.log(`${words.size} words on the pages, ${Object.keys(table).length} exceptions, ${(js.length / 1024).toFixed(1)} KB`);
