// Builds data/art.js and art/<image_id>.jpg for Collage: public-domain works from the
// Art Institute of Chicago API (CC0 images). Images are copied into the repo at 600px wide
// so the page never depends on the museum's image server.
// Usage: node tools/build-art.mjs
import fs from 'node:fs';

const TYPES = [['Painting', 120], ['Print', 30]];
const headers = { 'AIC-User-Agent': 'The Muze (github.com/TheCosmicKitchen/The-Muze)' };
const art = [];
for (const [type, want] of TYPES) {
  for (let page = 1; art.filter(a => a.k === type).length < want && page < 10; page++) {
    const q = new URLSearchParams({
      'query[bool][must][][term][is_public_domain]': 'true',
      fields: 'id,title,artist_title,date_display,image_id,color',
      limit: '100', page: String(page),
    });
    q.append('query[bool][must][][term][artwork_type_title.keyword]', type);
    const res = await fetch(`https://api.artic.edu/api/v1/artworks/search?${q}`, { headers });
    const { data } = await res.json();
    for (const d of data) {
      if (art.filter(a => a.k === type).length >= want) break;
      if (!d.image_id || !d.artist_title) continue;
      // Prints are often near-monochrome; keep the colourful ones.
      if (type === 'Print' && (!d.color || d.color.s < 30)) continue;
      art.push({ k: type, t: d.title, a: d.artist_title, d: d.date_display, i: d.image_id, id: d.id });
    }
  }
}

fs.mkdirSync('art', { recursive: true });
const ok = [];
for (let n = 0; n < art.length; n += 6) {
  await Promise.all(art.slice(n, n + 6).map(async w => {
    const file = `art/${w.i}.jpg`;
    if (!fs.existsSync(file)) {
      const res = await fetch(`https://www.artic.edu/iiif/2/${w.i}/full/600,/0/default.jpg`, { headers });
      if (!res.ok) return console.warn(`skip ${w.t} (${res.status})`);
      fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
    }
    ok.push(w);
  }));
}
const out = art.filter(w => ok.includes(w)).map(({ k, ...rest }) => rest);
fs.mkdirSync('data', { recursive: true });
fs.writeFileSync('data/art.js', `// Generated by tools/build-art.mjs from the Art Institute of Chicago API (public-domain works, CC0 images).\nwindow.ART=${JSON.stringify(out)};\n`);
console.log(`${out.length} works`);
